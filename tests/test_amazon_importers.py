class TestNormalizedModels(unittest.TestCase):
    """Model-level invariants."""

    def test_source_info_defaults_to_imported_excel(self) -> None:
        s = SourceInfo()
        self.assertEqual(s.source_type, "imported_excel")
        self.assertTrue(s.source_hash)

    def test_source_info_invalid_type_falls_back(self) -> None:
        s = SourceInfo(source_type="not_allowed")
        self.assertEqual(s.source_type, "imported_excel")

    def test_amazon_product_dedup_key_uses_asin_when_present(self) -> None:
        p = AmazonProduct(asin="B0TEST001", source_row=2)
        self.assertEqual(p.dedup_key(), "asin:B0TEST001")

    def test_amazon_product_dedup_key_falls_back_to_brand_title(self) -> None:
        p = AmazonProduct(brand="ACME", title="Widget", source_row=2)
        self.assertEqual(p.dedup_key(), "bt:ACME|Widget")

    def test_amazon_product_dedup_key_handles_missing_fields(self) -> None:
        p = AmazonProduct(source_row=2)
        self.assertEqual(p.dedup_key(), "bt:?|?")

    def test_search_appearance_dedup_key_includes_rank(self) -> None:
        s = AmazonSearchAppearance(
            keyword="kw", asin="B0TEST001", search_rank=5, source_row=2
        )
        self.assertEqual(s.dedup_key(), "kw|B0TEST001|5")

    def test_keyword_metric_dedup_key(self) -> None:
        k = KeywordMetric(keyword="chicken saddle", source_row=2)
        self.assertEqual(k.dedup_key(), "kw:chicken saddle")

    def test_brand_metric_dedup_key(self) -> None:
        b = BrandMetric(brand="ACME", source_row=2)
        self.assertEqual(b.dedup_key(), "brand:ACME")

    def test_seller_metric_dedup_key(self) -> None:
        s = SellerMetric(seller="SellerOne", source_row=2)
        self.assertEqual(s.dedup_key(), "seller:SellerOne")

    def test_category_metric_dedup_key(self) -> None:
        c = CategoryMetric(category="Poultry", source_row=2)
