class TestColumnAliases(unittest.TestCase):
    """Header normalisation and field-mapping behaviour."""

    def test_normalize_header_strips_units_and_whitespace(self) -> None:
        self.assertEqual(normalize_header("FBA($)"), "fba")
        self.assertEqual(normalize_header("Monthly  Sales"), "monthlysales")
        self.assertEqual(normalize_header("月 销\n量"), "月销量")
        self.assertEqual(normalize_header("FBA Fee (USD)"), "fbafee")
        self.assertEqual(normalize_header("  Rating(%)  "), "rating")
        self.assertEqual(normalize_header(""), "")
        self.assertEqual(normalize_header(None), "")  # type: ignore[arg-type]

    def test_normalize_header_drops_parenthesised_units(self) -> None:
        # ``(lbs)``, ``(cm)``, ``(in)`` etc. are stripped wholesale.
        self.assertEqual(normalize_header("Weight(lbs)"), "weight")
        self.assertEqual(normalize_header("Dimensions(cm)"), "dimensions")
        self.assertEqual(normalize_header("月销量（近30天）"), "月销量")

    def test_standard_fields_includes_canonical_name_as_first_alias(self) -> None:
        for std_field, aliases in STANDARD_FIELDS.items():
            self.assertEqual(aliases[0], std_field,
                             f"{std_field} must list itself first")

    def test_required_and_optional_keys_match_supported_types(self) -> None:
        for ftype in REQUIRED_FIELDS_BY_TYPE:
            self.assertIn(ftype, SUPPORTED_TYPES)
        for ftype in OPTIONAL_FIELDS_BY_TYPE:
            self.assertIn(ftype, SUPPORTED_TYPES)

    def test_build_column_mapping_exact_match(self) -> None:
        headers = ["ASIN", "Title", "Price", "Brand"]
        result = build_column_mapping(headers, "products")
        self.assertIsInstance(result, ColumnMappingResult)
        fields = {m.standard_field for m in result.mappings}
        self.assertIn("asin", fields)
        self.assertIn("title", fields)
        self.assertIn("price", fields)
        self.assertIn("brand", fields)
        for m in result.mappings:
            self.assertEqual(m.mapping_method, "exact")
            self.assertEqual(m.confidence, "high")

    def test_build_column_mapping_chinese_aliases(self) -> None:
        headers = ["商品ASIN", "商品标题", "售价", "品牌", "月销量", "评分数"]
        result = build_column_mapping(headers, "products")
        field_to_header = result.field_to_column
        self.assertIn("asin", field_to_header)
        self.assertIn("title", field_to_header)
        self.assertIn("price", field_to_header)
        self.assertIn("brand", field_to_header)
        self.assertIn("monthly_sales", field_to_header)
        self.assertIn("review_count", field_to_header)
        for m in result.mappings:
            self.assertEqual(m.mapping_method, "alias")
            self.assertEqual(m.confidence, "high")

    def test_build_column_mapping_handles_synonyms(self) -> None:
        # Multiple synonyms for monthly_sales.
        for raw in ("月销量", "近30天销量", "Monthly Sales", "Sales per Month", "30天销量", "月销"):
            result = build_column_mapping([raw], "products")
            self.assertIn("monthly_sales", result.field_to_column,
                          f"failed for synonym: {raw}")

    def test_build_column_mapping_unit_suffix_tolerance(self) -> None:
        # The same logical field with different unit suffixes should
        # collapse to the same standard field.
        for raw in ("FBA($)", "FBA费用", "FBA Fee", "Fulfillment Fee"):
            result = build_column_mapping([raw], "products")
            self.assertIn("fba_fee", result.field_to_column,
                          f"failed for variant: {raw}")

    def test_build_column_mapping_handles_whitespace_and_case(self) -> None:
        headers = ["  asin  ", "TITLE", "Price", "  Brand "]
        result = build_column_mapping(headers, "products")
        self.assertEqual(len(result.mappings), 4)
        self.assertEqual(set(result.field_to_column.keys()),
                         {"asin", "title", "price", "brand"})

    def test_build_column_mapping_reorders_columns(self) -> None:
        # Column ORDER must not matter — the loader resolves by name.
        forward = ["ASIN", "Title", "Price"]
        reverse = ["Price", "Title", "ASIN"]
        r1 = build_column_mapping(forward, "products")
        r2 = build_column_mapping(reverse, "products")
        self.assertEqual(set(r1.field_to_column.keys()),
                         set(r2.field_to_column.keys()))

    def test_unmapped_columns_kept_not_dropped(self) -> None:
        headers = ["ASIN", "Title", "Price", "Mystery Column", "Another Unknown"]
        result = build_column_mapping(headers, "products")
        self.assertIn("Mystery Column", result.unmapped_columns)
        self.assertIn("Another Unknown", result.unmapped_columns)
        self.assertEqual(len(result.unmapped_columns), 2)
        # Mapping warnings should mention the unmapped columns.
        self.assertTrue(any("unmapped" in w.lower() for w in result.mapping_warnings))

    def test_required_missing_reported(self) -> None:
        # Products requires asin/title/price — drop "price".
        result = build_column_mapping(["ASIN", "Title"], "products")
        self.assertIn("price", result.required_missing)
        self.assertTrue(any("required" in w.lower() for w in result.mapping_warnings))

    def test_optional_missing_reported(self) -> None:
        # Provide the bare required set only — every optional field
        # should appear in optional_missing.
        result = build_column_mapping(["ASIN", "Title", "Price"], "products")
        self.assertIn("brand", result.optional_missing)
        self.assertIn("monthly_sales", result.optional_missing)
        self.assertIn("fba_fee", result.optional_missing)

    def test_duplicate_headers_flagged(self) -> None:
        result = build_column_mapping(["ASIN", "ASIN", "Title"], "products")
        # Only one mapping is produced; the duplicate is flagged.
        asin_mappings = [m for m in result.mappings if m.standard_field == "asin"]
        self.assertEqual(len(asin_mappings), 1)
        self.assertTrue(any("duplicate" in w.lower() for w in result.mapping_warnings))

    def test_fuzzy_similarity_thresholds(self) -> None:
        # Identical strings -> 1.0.
        self.assertEqual(_fuzzy_similarity("asin", "asin"), 1.0)
        # Empty -> 0.
        self.assertEqual(_fuzzy_similarity("", "asin"), 0.0)
        # Short non-matching strings -> 0.
        self.assertEqual(_fuzzy_similarity("abc", "xyz"), 0.0)
        # Substring fallback for very short tokens.
        self.assertGreater(_fuzzy_similarity("ab", "abc"), 0.0)

    def test_fuzzy_match_emits_low_confidence(self) -> None:
        # "Tittle" is one char off "Title" — trigram similarity should
        # exceed the threshold and produce a low-confidence fuzzy match.
        result = build_column_mapping(["ASIN", "Tittle", "Price"], "products")
        title_mapping = [m for m in result.mappings if m.standard_field == "title"]
        if title_mapping:  # fuzzy may or may not fire depending on threshold
            self.assertEqual(title_mapping[0].mapping_method, "fuzzy")
            self.assertEqual(title_mapping[0].confidence, "low")


