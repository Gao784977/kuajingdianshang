class TestEndToEndDispatch(unittest.TestCase):
    """detect -> get_loader -> load pipeline."""

    def test_pipeline_for_each_fixture(self) -> None:
        cases = [
            ("products.xlsx", "products"),
            ("search.xlsx", "search"),
            ("keyword_analysis.xlsx", "keyword"),
            ("market_analysis.xlsx", "market"),
            ("category_analysis.xlsx", "category"),
            ("brand_analytics.xlsx", "brand_analytics"),
            ("brands.xlsx", "brands"),
            ("sellers.xlsx", "sellers"),
        ]
        for fname, expected_type in cases:
            with self.subTest(fixture=fname):
                fp = _fixture(fname)
                det = detect_workbook(fp)
                self.assertEqual(det.detected_type, expected_type,
                                 f"detection failed for {fname}")
                loader = get_loader(det.detected_type)
                self.assertIsNotNone(loader, f"no loader for {det.detected_type}")
                result = loader.load(fp)  # type: ignore[union-attr]
                self.assertGreater(result.row_count, 0,
                                   f"no rows loaded from {fname}")
                self.assertEqual(len(result.errors), 0,
                                 f"errors loading {fname}: {result.errors}")


