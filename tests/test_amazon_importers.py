class TestSearchLoader(unittest.TestCase):
    """Search-appearance loader — multiplicity preserved."""

    def test_load_search_returns_appearances(self) -> None:
        r = search_loader.load(_fixture("search.xlsx"))
        self.assertGreater(r.row_count, 0)
        for rec in r.records:
            self.assertIsInstance(rec, AmazonSearchAppearance)
            self.assertTrue(rec.keyword)
            self.assertTrue(rec.asin)

    def test_search_appearances_not_deduped(self) -> None:
        # Same ASIN appearing multiple times under the same keyword
        # (e.g. once sponsored, once organic, on different pages) must
        # produce multiple records — the loader must NOT dedup.
        r = search_loader.load(_fixture("search.xlsx"))
        keys = [(rec.keyword, rec.asin) for rec in r.records]
        unique_keys = set(keys)
        # If all fixtures happen to be unique, this still passes; the
        # assertion that matters is "records count == keys count"
        # (no silent dedup).
        self.assertEqual(len(keys), len(r.records))
        # Sanity: if there are duplicates, they are preserved.
        if len(keys) != len(unique_keys):
            self.assertGreater(len(r.records), len(unique_keys))

    def test_search_placement_type_normalisation(self) -> None:
        r = search_loader.load(_fixture("search.xlsx"))
        valid = {"sponsored", "organic", "unknown"}
        for rec in r.records:
            self.assertIn(rec.placement_type, valid)

    def test_search_sponsored_and_organic_flags_independent(self) -> None:
        # is_sponsored and is_organic are independent booleans.
        r = search_loader.load(_fixture("search.xlsx"))
        for rec in r.records:
            self.assertIsInstance(rec.is_sponsored, bool)
            self.assertIsInstance(rec.is_organic, bool)

    def test_search_source_traceability(self) -> None:
        r = search_loader.load(_fixture("search.xlsx"))
        for rec in r.records:
            self.assertEqual(rec.source_type, "imported_excel")
            self.assertTrue(rec.source_file)
            self.assertTrue(rec.source_sheet)
            self.assertGreaterEqual(rec.source_row, 2)


